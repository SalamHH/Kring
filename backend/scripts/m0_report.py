"""M0 report data (spec §9.5): offline replay tables and the 25-street review page.

    uv run python -m scripts.m0_report

Writes, from the recorded quarter and Kartverket recordings (no network for the replay):
- docs/m0/replay-tables.md: precision by county, method, category, Akershus municipality,
  and the most frequent unplaced area values.
- docs/m0/street-sample.html: 25 Oslo street-based placements on a map, each with the police
  text, for checking by hand whether the street is right (§9.5: ≥ 90 %).
"""

from __future__ import annotations

import asyncio
import hashlib
import html
import json
from collections import Counter
from pathlib import Path

from tests.quality import STREET_METHODS, Row, recorded_at, replay, summarise

OUT = Path(__file__).resolve().parents[2] / "docs" / "m0"
SAMPLE_SIZE = 25


def pct(x: float) -> str:
    return f"{x:.0%}"


def stable_order(r: Row) -> str:
    return hashlib.sha1(r.id.encode()).hexdigest()


def tables(rows: list[Row]) -> str:
    oslo = [r for r in rows if r.knr == "0301"]
    akershus = [r for r in rows if r.fylke == "32"]
    out = [
        "# M0 replay tables\n",
        f"Generated by `scripts/m0_report.py` from the quarter recorded {recorded_at()[:10]}.",
        "Controls (planned traffic controls) are excluded from every share.",
        "Uncertainty is as stored (rounded).\n",
        "## By county\n",
        "| | Incidents | Controls | ≤ 300 m | ≤ 500 m | ≤ 1 000 m | ≤ 2 000 m | Unplaced |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for name, rs in (("Oslo (gated)", oslo), ("Akershus (reported)", akershus)):
        s = summarise(rs)
        out.append(f"| {name} | {s.analysed} | {s.controls} | {pct(s.le_300)} | {pct(s.le_500)} | "
                   f"{pct(s.le_1000)} | {pct(s.le_2000)} | {pct(s.unplaced)} |")  # fmt: skip

    out += ["\n## By placement method\n", "| Method | Oslo | Akershus |", "|---|---:|---:|"]
    so, sa = summarise(oslo), summarise(akershus)
    for m in sorted(set(so.methods) | set(sa.methods), key=lambda m: -(so.methods[m] + sa.methods[m])):
        out.append(f"| {m} | {so.methods[m]} ({so.methods[m] / so.analysed:.0%}) | "
                   f"{sa.methods[m]} ({sa.methods[m] / sa.analysed:.0%}) |")  # fmt: skip

    out += ["\n## By tier\n", "| Tier | Oslo | Akershus |", "|---|---:|---:|"]
    for t in ("gate", "nabolag", "bydel"):
        out.append(f"| {t} | {pct(so.tiers[t] / so.analysed)} | {pct(sa.tiers[t] / sa.analysed)} |")

    out += ["\n## Oslo by category\n", "| Category | n | ≤ 500 m | ≤ 1 000 m |", "|---|---:|---:|---:|"]
    cats = Counter(r.category for r in oslo if not r.is_control)
    for c, _ in cats.most_common():
        s = summarise([r for r in oslo if r.category == c])
        out.append(f"| {c} | {s.analysed} | {pct(s.le_500)} | {pct(s.le_1000)} |")

    out += ["\n## Akershus by municipality\n", "| Municipality | n | ≤ 500 m | ≤ 1 000 m | Unplaced |",
            "|---|---:|---:|---:|---:|"]  # fmt: skip
    kommuner = Counter(r.kommune for r in akershus if not r.is_control)
    for k, _ in kommuner.most_common():
        s = summarise([r for r in akershus if r.kommune == k])
        out.append(f"| {k} | {s.analysed} | {pct(s.le_500)} | {pct(s.le_1000)} | {pct(s.unplaced)} |")

    for name, rs in (("Oslo", oslo), ("Akershus", akershus)):
        unplaced = Counter(
            (r.area or "(empty)") for r in rs if not r.is_control and not r.placement.has_point
        )
        top = " · ".join(f"{a} {n}" for a, n in unplaced.most_common(15))
        out += [f"\n## Most frequent unplaced area values, {name}\n", top]
    return "\n".join(out) + "\n"


PAGE = (Path(__file__).parent / "street_sample.html").read_text("utf-8")


def street_sample(rows: list[Row]) -> tuple[str, list[Row]]:
    pool = [r for r in rows if r.knr == "0301" and not r.is_control and r.placement.method in STREET_METHODS]
    sample = sorted(pool, key=stable_order)[:SAMPLE_SIZE]
    data = [
        {"id": r.id, "category": r.category, "area": r.area, "text": r.text, "match": r.placement.match,
         "method": r.placement.method, "unc": r.uncertainty, "lat": r.placement.lat, "lon": r.placement.lon}
        for r in sample
    ]  # fmt: skip
    page = (
        PAGE.replace("__DATA__", json.dumps(data, ensure_ascii=False).replace("</", "<\\/"))
        .replace("__N__", str(len(sample)))
        .replace("__REC__", html.escape(recorded_at()[:10]))
    )
    return page, sample


def main() -> None:
    rows = asyncio.run(replay())
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "replay-tables.md").write_text(tables(rows), "utf-8")
    page, sample = street_sample(rows)
    (OUT / "street-sample.html").write_text(page, "utf-8")
    print(f"wrote {OUT / 'replay-tables.md'} and {OUT / 'street-sample.html'} ({len(sample)} placements)")


if __name__ == "__main__":
    main()
